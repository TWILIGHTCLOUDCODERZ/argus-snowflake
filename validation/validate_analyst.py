def grade_q1_strict(rows):
    """Q1: must include BOTH consolidation hubs, no account outside planted rings."""
    got = _get_all_ids(rows, "account_id")
    if not got:
        return False, "No rows returned; expected hub accounts A0000095 and A0000046"
    want = members("RING-001", {"consolidation"}) | members("RING-005", {"consolidation"})
    missing = want - got
    if missing:
        return False, f"Missing hub(s) {sorted(missing)}; got {sorted(got)}"
    # Precision: no account outside planted rings
    outside = got - ALL_RING_ACCOUNTS
    if outside:
        return False, f"Returned account(s) outside planted rings: {sorted(outside)}"
    return True, f"Both hubs {sorted(want)} found; {len(got)} account(s) total, all within planted rings"


def grade_q2_strict(rows, account_id):
    """Q2: must return >=1 row that is a cross-bank transaction for the account.
    Filing judgement deferred to Verifier agent (Week 3)."""
    if not rows:
        return False, f"No rows for {account_id}; expected cross-bank transaction evidence"
    has_cross_bank = False
    for r in rows:
        cb = _get(r, "counterparty_bank", "detail")
        direction = _get(r, "direction")
        evidence_type = _get(r, "evidence_type", "type", "signal_type", "alert_type")
        bank_id = _get(r, "bank_id")
        source_banks = _get(r, "source_banks", "hub_source_banks")

        # Explicit cross-bank evidence type labels
        if evidence_type and any(k in str(evidence_type).lower() for k in ("cross_bank", "hub_account", "hub_detection")):
            has_cross_bank = True
            break
        # Counterparty bank from a different bank
        if cb and cb in BANKS and bank_id and cb != bank_id:
            has_cross_bank = True
            break
        # Credit from consortium bank
        if cb and cb in BANKS and direction in ("credit", "debit"):
            has_cross_bank = True
            break
        # Any consortium bank counterparty
        if cb and cb in BANKS:
            has_cross_bank = True
            break
        # Hub account detection data (source_banks >= 2 means cross-bank)
        if source_banks is not None:
            try:
                if int(source_banks) >= 2:
                    has_cross_bank = True
                    break
            except (ValueError, TypeError):
                pass
        # Inbound amount from hub accounts (evidence of cross-bank activity)
        inbound = _get(r, "inbound_amount", "hub_inbound_amount", "alert_inbound_amount")
        if inbound is not None:
            try:
                if float(inbound) > 0:
                    has_cross_bank = True
                    break
            except (ValueError, TypeError):
                pass

    if not has_cross_bank:
        return False, f"{account_id}: {len(rows)} row(s) but none show cross-bank evidence"
    return True, f"{account_id}: {len(rows)} row(s) with cross-bank evidence [NOTE: filing decision deferred to Verifier agent]"


def grade_q3_strict(rows):
    """Q3: must include RING-002's national_id hash at 3 banks."""
    if not rows:
        return False, "No rows returned"
    nid_hash = rings["RING-002"]["shared_national_id_hash"]  # 7970862ea9073fd80960309b
    nid_row = None
    for r in rows:
        ih = _get(r, "identifier_hash")
        if ih == nid_hash:
            nid_row = r
            break
    if not nid_row:
        return False, f"RING-002 national_id_hash {nid_hash} not in {len(rows)} rows"
    bank_count = int(_get(nid_row, "contributing_bank_count", "signal_bank_count", default=0))
    if bank_count < 3:
        return False, f"national_id at {bank_count} banks, expected 3"
    return True, f"RING-002 national_id_hash found at {bank_count} banks; {len(rows)} total signals"


def grade_q4_strict(rows):
    """Q4: must return RING-003 account A0000343 and NO other account."""
    got = _get_all_ids(rows, "account_id", "structuring_account_id")
    want = members("RING-003")  # {A0000343}
    if not got:
        return False, f"No accounts returned; expected {sorted(want)}"
    if want != got:
        extra = got - want
        missing = want - got
        parts = []
        if missing:
            parts.append(f"missing {sorted(missing)}")
        if extra:
            parts.append(f"extra {sorted(extra)}")
        return False, f"Got {sorted(got)}; {'; '.join(parts)}"
    return True, f"Exactly A0000343 returned (RING-003 structuring account)"


def make_grade_q5_strict(q5_truth):
    """Q5: must have >=1 HIGH gap for RING-001; every gap flag must match ground truth."""
    def grade_q5_strict(rows):
        if not rows:
            return False, "No rows returned for RING-001 obligations"
        has_high_gap = False
        mismatches = []
        for r in rows:
            oid = _get(r, "obligation_id")
            is_gap = _get(r, "is_gap", "exposure_is_gap")
            severity = str(_get(r, "severity", "exposure_severity", default="")).upper()

            if oid and oid in q5_truth:
                truth_gap = q5_truth[oid]["is_gap"]
                truth_sev = q5_truth[oid]["severity"]
                # Normalize is_gap to bool
                got_gap = is_gap in (True, "true", "True", 1, "1", "TRUE")
                expected_gap = truth_gap in (True, "true", "True", 1, "1", "TRUE")
                if got_gap != expected_gap:
                    mismatches.append(f"{oid}: is_gap={got_gap} expected {expected_gap}")
            if is_gap in (True, "true", "True", 1, "1", "TRUE") and severity == "HIGH":
                has_high_gap = True

        if mismatches:
            return False, f"Gap flag mismatch: {'; '.join(mismatches[:3])}"
        if not has_high_gap:
            return False, f"No HIGH gap found in {len(rows)} rows"
        return True, f"RING-001: {len(rows)} obligations, has HIGH gap(s), all flags match ground truth"
    return grade_q5_strict


def make_grade_q6_strict(ground_truth_value):
    """Q6: numeric answer within +/-1% of verified SQL result."""
    def grade_q6_strict(rows):
        if not rows:
            return False, f"No rows returned; expected value near AED {ground_truth_value:,.2f}"

        # Look for the value in known column names
        val, col = _first_positive_numeric(
            rows,
            "value_through_hubs", "total_amount", "total_hub_inbound_amount",
            "hub_inbound_amount", "cross_bank_amount", "amount", "inbound_amount",
            "total_value", "sum_amount", "value"
        )

        # Fallback: scan all numeric columns in first row
        if val is None:
            for k, v in rows[0].items():
                if v is not None and k not in ("typology_id", "role", "entity_type", "hub_accounts", "entity_id"):
                    try:
                        fv = float(v)
                        if fv > 100:  # filter out counts
                            val = fv
                            col = k
                            break
                    except (ValueError, TypeError):
                        pass

        if val is None:
            return False, f"No positive numeric value found in columns {list(rows[0].keys())}"

        # Check if it's just a count (small integer) rather than a monetary value
        if val < 1000:
            return False, f"Value {val} looks like a count, not a monetary amount (expected ~AED {ground_truth_value:,.0f})"

        tolerance = ground_truth_value * 0.01
        diff = abs(val - ground_truth_value)
        pct = (diff / ground_truth_value) * 100 if ground_truth_value else 0

        if diff <= tolerance:
            return True, f"AED {val:,.2f} (column: {col}) within 1% of ground truth AED {ground_truth_value:,.2f} (diff: {pct:.2f}%)"
        return False, f"AED {val:,.2f} (column: {col}) differs from ground truth AED {ground_truth_value:,.2f} by {pct:.1f}% (tolerance: 1%)"
    return grade_q6_strict



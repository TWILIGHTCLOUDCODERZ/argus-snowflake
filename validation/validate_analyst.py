# ─── helpers ────────────────────────────────────────────────────────
def members(tid, roles=None):
    return {m["entity_id"] for m in rings[tid]["members"]
            if m["entity_type"] == "account" and (roles is None or m["role"] in roles)}


def call_analyst(con, question: str, view: str) -> dict:
    try:
        resp = con.rest.request(
            "/api/v2/cortex/analyst/message",
            body={
                "messages": [{"role": "user", "content": [{"type": "text", "text": question}]}],
                "semantic_view": view
            },
            method="post",
            client="rest"
        )
        return resp
    except Exception as e:
        return {"error": f"REST API error: {e}"}


def extract_sql(analyst_response: dict) -> str | None:
    if "error" in analyst_response:
        return None
    msg = analyst_response.get("message", {})
    for block in msg.get("content", []):
        if block.get("type") == "sql":
            stmt = block.get("statement", "").strip()
            stmt = re.sub(r'\s*--\s*Generated by Cortex Analyst.*$', '', stmt, flags=re.MULTILINE).strip()
            if stmt.endswith(";"):
                stmt = stmt[:-1].strip()
            return stmt
    raw = json.dumps(analyst_response)
    m = re.search(r"```sql\s*\n(.*?)```", raw, re.DOTALL | re.IGNORECASE)
    if m:
        return m.group(1).strip()
    return None


def run_sql(cur, sql: str) -> list[dict]:
    cur.execute(sql)
    cols = [d[0].lower() for d in cur.description]
    return [dict(zip(cols, row)) for row in cur.fetchall()]


def _get_all_ids(rows, *candidates):
    ids = set()
    for r in rows:
        for c in candidates:
            v = r.get(c)
            if v is not None and str(v).strip():
                ids.add(str(v).strip())
    return ids


def _get(row, *candidates, default=None):
    for c in candidates:
        if c in row and row[c] is not None:
            return row[c]
    return default


def _first_positive_numeric(rows, *col_candidates):
    """Return the first positive numeric value found across candidate columns."""
    for col in col_candidates:
        for r in rows:
            val = r.get(col)
            if val is not None:
                try:
                    fv = float(val)
                    if fv > 0:
                        return fv, col
                except (ValueError, TypeError):
                    pass
    return None, None



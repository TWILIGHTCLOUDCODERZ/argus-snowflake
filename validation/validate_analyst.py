# ─── main evaluation loop ─────────────────────────────────────────
def evaluate_set(con, cur, questions, set_label):
    results = []
    for q in questions:
        qid = q["qid"]
        print(f"\n[{qid}] {q['question'][:90]}...")

        analyst_resp = call_analyst(con, q["question"], q["view"])
        sql = extract_sql(analyst_resp)

        entry = {
            "qid": qid,
            "question": q["question"],
            "view": q["view"],
            "set": q["set"],
            "analyst_response": analyst_resp,
            "generated_sql": sql,
            "pass": False,
            "reason": ""
        }

        if not sql:
            err = analyst_resp.get("error", "No SQL extracted from response")
            entry["reason"] = f"FAILED: {err}"
            print(f"  -> FAIL: {err}")
            results.append(entry)
            continue

        print(f"  SQL extracted ({len(sql)} chars)")

        try:
            rows = run_sql(cur, sql)
            print(f"  {len(rows)} row(s) returned")
        except Exception as e:
            entry["reason"] = f"SQL execution error: {e}"
            print(f"  -> FAIL: SQL error: {e}")
            results.append(entry)
            continue

        try:
            passed, reason = q["grader"](rows)
            entry["pass"] = passed
            entry["reason"] = reason
            print(f"  -> {'PASS' if passed else 'FAIL'}: {reason}")
        except Exception as e:
            entry["reason"] = f"Grading error: {traceback.format_exc()}"
            print(f"  -> FAIL: grading error: {e}")

        results.append(entry)
        time.sleep(1)

    return results


